#!/usr/bin/env python3
"""Compress baked PNG sheets to WebP and write per-faction JS bundles.

assets/sprites/<faction>/*.png  ->  assets/sprites/<faction>/*.webp
                                ->  assets/sprites/<faction>.bundle.js
The bundles carry the images as data URIs plus the manifest entries, so
the game can load them with a plain <script> tag (works from file://).
"""
import base64, json, os, sys
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SPR = os.path.join(ROOT, 'assets', 'sprites')
manifest = json.load(open(os.path.join(SPR, 'manifest.json')))
QUALITY = int(os.environ.get('WEBP_QUALITY', '86'))

bundles = {}
total = 0
for key, ent in manifest['sprites'].items():
    faction = ent['file'].split('/')[0]
    entry = dict(ent)
    for part, lossless in (('', False), ('.mask', False)):
        src = os.path.join(SPR, ent['file'] + part + '.png')
        dst = os.path.join(SPR, ent['file'] + part + '.webp')
        im = Image.open(src).convert('RGBA')
        if part == '.mask':
            # only the alpha matters: store it as a single gray channel
            a = im.split()[3]
            im = Image.merge('RGBA', (a, a, a, Image.new('L', a.size, 255)))
            im.save(dst, 'WEBP', quality=80, method=6)
        else:
            im.save(dst, 'WEBP', quality=QUALITY, alpha_quality=90, method=6)
        data = open(dst, 'rb').read()
        total += len(data)
        entry['mask' if part else 'color'] = 'data:image/webp;base64,' + base64.b64encode(data).decode()
    bundles.setdefault(faction, {})[key] = entry

for faction, entries in bundles.items():
    path = os.path.join(SPR, faction + '.bundle.js')
    with open(path, 'w') as f:
        f.write('// Generated by tools/asset-baker/pack.py - do not edit\n')
        f.write('(window.XFIRE_ASSETS = window.XFIRE_ASSETS || {})[%s] = %s;\n' % (json.dumps(faction), json.dumps(entries)))
    print(faction, round(os.path.getsize(path) / 1e6, 2), 'MB')
print('webp total', round(total / 1e6, 2), 'MB')

# ---- IRONCLAD: top-down sheets -> assets/sprites/ironclad.bundle.js ----
IC = os.path.join(SPR, 'ironclad')
meta_path = os.path.join(IC, 'ironclad.json')
if os.path.exists(meta_path):
    meta = json.load(open(meta_path))
    out, total = {}, 0
    def uri(src, dst, gray):
        im = Image.open(src).convert('RGBA')
        if gray:
            a = im.split()[3]
            im = Image.merge('RGBA', (a, a, a, Image.new('L', a.size, 255)))
            im.save(dst, 'WEBP', quality=80, method=6)
        else:
            im.save(dst, 'WEBP', quality=QUALITY, alpha_quality=90, method=6)
        data = open(dst, 'rb').read()
        return 'data:image/webp;base64,' + base64.b64encode(data).decode(), len(data)
    for name, ent in meta.items():
        e = {'cell': ent['cell'], 'dirs': ent['dirs'], 'ref': ent['ref']}
        for part, gray in (('', False), ('.mask', True), ('.shadow', True)):
            src = os.path.join(IC, name + part + '.png')
            if not os.path.exists(src) or (part == '.shadow' and not ent.get('shadow')):
                continue
            e['color' if not part else part[1:]], n = uri(src, os.path.join(IC, name + part + '.webp'), gray)
            total += n
        out[name] = e
    path = os.path.join(SPR, 'ironclad.bundle.js')
    with open(path, 'w') as f:
        f.write('// Generated by tools/asset-baker/pack.py - do not edit\n')
        f.write('window.IRONCLAD_ASSETS = %s;\n' % json.dumps(out))
    print('ironclad', round(os.path.getsize(path) / 1e6, 2), 'MB')
